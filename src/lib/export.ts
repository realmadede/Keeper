import { getCategoryMeta, type Household, type Transaction } from "../types";
import type { WeeklySummary, WeekWindow } from "./analytics";
import { formatTZS } from "./format";

export function buildWeeklyWhatsAppSummary(
  household: Household,
  week: WeekWindow,
  summary: WeeklySummary,
): string {
  const lines: string[] = [
    `*${household.name} — Weekly Budget Summary*`,
    `Period: ${week.label} (${week.startISO} to ${week.endISO})`,
    "",
    `Weekly Target: ${formatTZS(household.weekly_budget_target)}`,
    `Contributed: ${formatTZS(summary.totalContributed)}`,
    `Spent: ${formatTZS(summary.totalSpent)}`,
    `Weekly Remaining: ${formatTZS(summary.remainingBalance)}`,
    `Cash on Hand (All-Time Pool): ${formatTZS(summary.allTimeBalance)}`,
    "",
    "*Member Contributions:*",
  ];

  for (const status of summary.memberStatuses) {
    const label =
      status.contributedThisWeek >= status.expectedShare && status.expectedShare > 0
        ? "Paid"
        : status.contributedThisWeek > 0
          ? "Partial"
          : "Pending";
    lines.push(
      `- ${status.member.profile.full_name}: ${formatTZS(status.contributedThisWeek)} / ${formatTZS(status.expectedShare)} (${label})`,
    );
  }

  if (summary.categories.length > 0) {
    lines.push("", "*Top Spending Categories:*");
    for (const cat of summary.categories) {
      lines.push(`- ${cat.label}: ${formatTZS(cat.amount)} (${cat.percent}%)`);
    }
  }

  lines.push("", "Generated by Keeper");
  return lines.join("\n");
}

function escapeCsvCell(value: string): string {
  if (/[",\r\n]/.test(value)) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

export function buildLedgerCsv(transactions: Transaction[]): string {
  const headers = [
    "Date",
    "Type",
    "Category",
    "Description",
    "Amount_TZS",
    "Paid_By",
    "Recorded_By",
    "Edited",
  ];

  const rows = transactions.map((tx) => {
    const catLabel = getCategoryMeta(tx.category).label;
    const recordedBy = tx.recorder?.full_name ?? "Household Member";
    const paidBy =
      tx.type === "contribution"
        ? tx.payer?.full_name ?? recordedBy
        : recordedBy;
    const edited = tx.updated_at ? "Yes" : "No";
    return [
      tx.transaction_date,
      tx.type === "contribution" ? "Contribution" : "Expense",
      catLabel,
      tx.description,
      String(tx.amount),
      paidBy,
      recordedBy,
      edited,
    ]
      .map(escapeCsvCell)
      .join(",");
  });

  return [headers.join(","), ...rows].join("\n");
}

export function downloadTextFile(filename: string, content: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
